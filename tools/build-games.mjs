// Builds app/core/games/dota2.js, the trimmed Dota 2 key list and hero
// abilities the action templates offer, from MGI Stream Control's game DB
// (server/games/dota2.json, dota2_heroes.json). Rerun after that DB changes:
//   node tools/build-games.mjs [path to mgi-stream-control]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(process.argv[2] ?? path.join(here, "..", "..", "mgi-stream-control"), "server", "games");
const game = JSON.parse(fs.readFileSync(path.join(src, "dota2.json"), "utf8"));
const db = JSON.parse(fs.readFileSync(path.join(src, "dota2_heroes.json"), "utf8"));

// Keys with no default bind cannot be pressed by a template.
const actions = game.actions
  .filter((a) => a.default_key)
  .map((a) => ({
    id: a.id,
    ru: a.name_ru,
    en: a.name_en,
    code: a.default_key,
    mods: a.default_mods ?? [],
    hold: a.press === "hold",
    repeat: a.repeat ?? 1,
    risky: a.danger === "high",
  }));

const heroes = db.heroes
  .map((h) => ({
    ru: h.name_ru,
    en: h.name_en,
    // Only what a key press does something with: no passives, nothing unbound.
    skills: h.abilities
      .filter((a) => a.action && !a.passive)
      .map((a) => ({ ru: a.name_ru, en: a.name_en, slot: a.action, needs: a.requires ?? undefined })),
  }))
  .filter((h) => h.skills.length)
  .sort((a, b) => a.ru.localeCompare(b.ru, "ru"));

const out = `// Generated by tools/build-games.mjs from MGI Stream Control's game DB. Do not edit by hand.
export const DOTA2 = ${JSON.stringify({ exe: game.exe[0], actions, heroes })};
`;
const file = path.join(here, "..", "app", "core", "games", "dota2.js");
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out);
console.log(`${actions.length} actions, ${heroes.length} heroes, ${(out.length / 1024).toFixed(1)} KB -> ${file}`);
